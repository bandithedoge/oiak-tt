  logic eq;
  logic gt;
} out_t;

typedef struct packed {
  logic [bits_per_residue_0-1:0] first;
  logic [bits_per_residue_1-1:0] second;
  logic [bits_per_residue_2-1:0] third;
} rns_t;

module mdf (
    output out_t out,
    input  logic clk,
    input  logic rst,
    input  rns_t a,
    input  rns_t b
);

  logic [bits-1:0] D_a, D_b;
  out_t out_next;

  assign D_a = (a.first * k_0 + a.second * k_1 + a.third * k_2);
  assign D_b = (b.first * k_0 + b.second * k_1 + b.third * k_2);
  assign out_next = D_a < D_b ? 3'b100 : (D_a > D_b ? 3'b001 : 3'b010);

  always_ff @(posedge clk) begin
    if (rst) out <= 0;
    else out <= out_next;
  end

endmodule

